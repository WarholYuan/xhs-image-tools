"""清理后补一刀：remove-ai-watermarks 只删它认得的标记（C2PA、生成参数、IPTC 的 AI 来源、生图软件名），
写在普通字段里的 AI 字样（描述里的提示词、作者写 ChatGPT）它不管。只处理图片，不处理视频。
这个脚本扫出这些字样，fix 时只删含这些字样的那几段，不动画面、不重新编码。

    uv run ai_text.py check 文件或文件夹 ...      有 AI 字样退出码 1，没有 0
    uv run ai_text.py fix   文件或文件夹 ...      就地删掉含 AI 字样的字段（只用在 _clean 输出上，不碰原文件）

图片：JPEG / PNG / WebP 看 EXIF（含子目录的用户注释）、XMP、PNG 文字块、JPEG 注释。
"""

from __future__ import annotations

import pathlib
import re
import struct
import sys

sys.dont_write_bytecode = True

KEYWORDS = [
    r"\bAI\b", r"AIGC", r"AI[- ]?generated", r"made with ai", r"generated by", r"trainedAlgorithmicMedia",
    r"compositeWithTrainedAlgorithmicMedia", r"Midjourney", r"Stable ?Diffusion", r"SDXL", r"ComfyUI",
    r"Automatic1111", r"InvokeAI", r"DALL[·-]?E", r"ChatGPT", r"OpenAI", r"gpt-image", r"Gemini", r"Imagen",
    r"Nano ?Banana", r"Sora", r"\bVeo\b", r"Runway", r"Pika", r"Kling", r"Firefly", r"Leonardo", r"Ideogram",
    r"Flux", r"Seedream", r"Jimeng", r"Doubao", r"即梦", r"豆包", r"可灵", r"海螺", r"通义", r"文心", r"混元",
    r"智谱", r"人工智能", r"AI生成", r"AI 生成", r"生成式", r"提示词", r"\bprompt\b", r"negative prompt",
    r"Steps: \d", r"Sampler:", r"CFG scale", r"\bSeed: \d",
]
PAT = re.compile("|".join(KEYWORDS), re.I)
IMAGE_EXT = {".jpg", ".jpeg", ".png", ".webp"}


def hit(text) -> str | None:
    if isinstance(text, bytes):
        text = text.decode("utf-8", "ignore") + " " + text.decode("utf-16-le", "ignore")
    m = PAT.search(str(text))
    return m.group(0) if m else None


def files_of(args: list[str]) -> list[pathlib.Path]:
    out = []
    for a in args:
        p = pathlib.Path(a).expanduser().resolve()
        if p.is_dir():
            out += sorted(f for f in p.iterdir() if f.is_file() and not f.name.startswith(".")
                          and f.suffix.lower() in IMAGE_EXT)
        elif p.exists():
            out.append(p)
        else:
            print(f"找不到：{p}", file=sys.stderr)
    return out


# ---------------- 图片 ----------------

def exif_hits(ex) -> list[tuple[str, int, int]]:
    """返回 [(所在目录, 标签号, 命中词)]。所在目录：0 主目录，0x8769 拍摄参数子目录。"""
    out = []
    for tag, v in ex.items():
        if tag in (0x8769, 0x8825):
            continue
        h = hit(v)
        if h:
            out.append((0, tag, h))
    for tag, v in ex.get_ifd(0x8769).items():
        h = hit(v)
        if h:
            out.append((0x8769, tag, h))
    return out


def scan_image(p: pathlib.Path) -> list[str]:
    from PIL import Image
    found = []
    with Image.open(p) as im:
        for ifd, tag, h in exif_hits(im.getexif()):
            found.append(f"EXIF {tag:#06x}：{h}")
        for k, v in im.info.items():
            if k in ("exif", "icc_profile", "dpi", "jfif", "jfif_version", "jfif_unit", "jfif_density"):
                continue
            h = hit(v)
            if h:
                found.append(f"{k}：{h}")
    if p.suffix.lower() in (".jpg", ".jpeg"):
        for marker, seg in jpeg_segments(p.read_bytes())[1]:
            if marker == 0xFE and hit(seg[2:]):
                found.append(f"JPEG 注释：{hit(seg[2:])}")
            if marker == 0xE1 and seg[2:31].startswith(b"http://ns.adobe.com/xap/1.0/") and hit(seg):
                found.append(f"XMP：{hit(seg)}")
    return sorted(set(found))


def jpeg_segments(data: bytes):
    """拆成 (SOI 之后、扫描数据之前的段列表, 剩下的原样字节)。"""
    if data[:2] != b"\xff\xd8":
        raise ValueError("不是 JPEG")
    i, segs = 2, []
    while i < len(data):
        marker = data[i + 1]
        if marker == 0xDA:
            return data[:2], segs, data[i:]
        n = struct.unpack(">H", data[i + 2:i + 4])[0]
        segs.append((marker, data[i + 2:i + 2 + n]))
        i += 2 + n
    raise ValueError("JPEG 没有扫描数据")


def clean_exif_bytes(raw_exif: bytes) -> bytes | None:
    """删掉含 AI 字样的 EXIF 标签，返回新的 EXIF 字节（带 Exif\\0\\0 头）；删完空了返回 None。"""
    from PIL import Image
    ex = Image.Exif()
    ex.load(raw_exif)
    hits = exif_hits(ex)
    if not hits:
        return raw_exif
    sub = ex.get_ifd(0x8769)
    for ifd, tag, _ in hits:
        if ifd == 0:
            del ex[tag]
        else:
            del sub[tag]
    if not any(t for t in ex if t not in (0x8769,)) and not sub:
        return None
    b = ex.tobytes()
    return b if b.startswith(b"Exif") else b"Exif\x00\x00" + b


def fix_jpeg(data: bytes) -> bytes:
    soi, segs, rest = jpeg_segments(data)
    out = bytearray(soi)
    for marker, seg in segs:
        body = seg[2:]
        if marker == 0xFE and hit(body):
            continue
        if marker == 0xE1 and body.startswith(b"Exif\x00\x00"):
            new = clean_exif_bytes(body)
            if new is None:
                continue
            seg = struct.pack(">H", len(new) + 2) + new
        elif marker == 0xE1 and hit(body):  # XMP 里有 AI 字样，整段去掉
            continue
        out += bytes([0xFF, marker]) + seg
    return bytes(out + rest)


def fix_png(data: bytes) -> bytes:
    out, i = bytearray(data[:8]), 8
    while i < len(data):
        n = struct.unpack(">I", data[i:i + 4])[0]
        kind = data[i + 4:i + 8]
        chunk = data[i:i + 12 + n]
        i += 12 + n
        if kind in (b"tEXt", b"zTXt", b"iTXt"):
            text = chunk[8:8 + n]
            if kind == b"zTXt":
                import zlib
                k, _, rest = text.partition(b"\x00")
                try:
                    text = k + b" " + zlib.decompress(rest[1:])
                except zlib.error:
                    pass
            if hit(text):
                continue
        if kind == b"eXIf":
            new = clean_exif_bytes(b"Exif\x00\x00" + chunk[8:8 + n])
            if new is None:
                continue
            body = new[6:]
            import zlib
            chunk = struct.pack(">I", len(body)) + b"eXIf" + body + struct.pack(">I", zlib.crc32(b"eXIf" + body) & 0xFFFFFFFF)
        out += chunk
        if kind == b"IEND":
            break
    return bytes(out)


def fix_webp(data: bytes) -> bytes:
    body, i = bytearray(), 12
    flags_at = None
    drop_exif = drop_xmp = False
    while i + 8 <= len(data):
        kind = data[i:i + 4]
        n = struct.unpack("<I", data[i + 4:i + 8])[0]
        chunk = bytearray(data[i:i + 8 + n + (n & 1)])
        i += 8 + n + (n & 1)
        if kind == b"XMP " and hit(chunk[8:8 + n]):
            drop_xmp = True
            continue
        if kind == b"EXIF":
            new = clean_exif_bytes(b"Exif\x00\x00" + bytes(chunk[8:8 + n]))
            if new is None:
                drop_exif = True
                continue
            payload = new[6:]
            chunk = bytearray(b"EXIF" + struct.pack("<I", len(payload)) + payload + (b"\x00" if len(payload) & 1 else b""))
        if kind == b"VP8X":
            flags_at = len(body) + 8
        body += chunk
    if flags_at is not None:
        if drop_exif:
            body[flags_at] &= ~0x08 & 0xFF
        if drop_xmp:
            body[flags_at] &= ~0x04 & 0xFF
    return b"RIFF" + struct.pack("<I", 4 + len(body)) + b"WEBP" + bytes(body)


# ---------------- 命令 ----------------

def scan(p: pathlib.Path) -> list[str]:
    return scan_image(p)


def fix(p: pathlib.Path) -> None:
    fn = {".png": fix_png, ".webp": fix_webp}.get(p.suffix.lower(), fix_jpeg)
    p.write_bytes(fn(p.read_bytes()))


def main() -> int:
    if len(sys.argv) < 3 or sys.argv[1] not in ("check", "fix"):
        print(__doc__)
        return 2
    cmd, paths = sys.argv[1], files_of(sys.argv[2:])
    left = 0
    for p in paths:
        try:
            found = scan(p)
            if found and cmd == "fix":
                fix(p)
                after = scan(p)
                print(f"  {'✓' if not after else '✗'} {p.name}：删掉 {len(found)} 处 AI 字样（{'；'.join(found)}）"
                      + (f"，还剩：{'；'.join(after)}" if after else ""))
                left += bool(after)
            elif found:
                print(f"  ✗ {p.name}：还有 AI 字样：{'；'.join(found)}")
                left += 1
            else:
                print(f"  ✓ {p.name}：没有 AI 字样")
        except Exception as e:  # 单个文件出错不影响别的
            print(f"  ✗ {p.name}：{e}")
            left += 1
    return 1 if left else 0


if __name__ == "__main__":
    raise SystemExit(main())
